// Why: an OMP turn can end with async jobs (background bash, eval cells) still running, and no
// lifecycle event fires when one finishes without waking the agent. The session's own job
// snapshot is the authority: report its count at agent_end and re-read it until the jobs finish.
export function getOmpBackgroundJobsSourceLines(): string[] {
  return [
    'const OMP_BACKGROUND_JOBS_POLL_MS = 5_000',
    '// Why renew: a post lost while the receiver restarts must not strand the pane for the whole job.',
    'const OMP_BACKGROUND_JOBS_RENEW_POLLS = 6',
    '// Why back off, not stop: while the session lives, a snapshot that reads again must still land.',
    'const OMP_BACKGROUND_JOBS_UNREADABLE_BACKOFF_POLLS = 12',
    'const OMP_BACKGROUND_JOBS_BACKOFF_MS = 60_000',
    'type OmpJobsContext = { getAsyncJobSnapshot?: () => { running?: unknown } | null }',
    'let ompBackgroundJobsTimer: ReturnType<typeof setTimeout> | null = null',
    '',
    '/** Running jobs; 0 without a job manager; null when the snapshot could not be read. */',
    'function runningOmpAsyncJobCount(ctx: OmpJobsContext | undefined): number | null {',
    "  if (typeof ctx?.getAsyncJobSnapshot !== 'function') return 0",
    '  try {',
    '    const snapshot = ctx.getAsyncJobSnapshot()',
    '    if (snapshot === null) return 0',
    '    return Array.isArray(snapshot?.running) ? snapshot.running.length : null',
    '  } catch {',
    '    return null',
    '  }',
    '}',
    '',
    'function stopOmpBackgroundJobsWatch(): void {',
    '  if (ompBackgroundJobsTimer !== null) clearTimeout(ompBackgroundJobsTimer)',
    '  ompBackgroundJobsTimer = null',
    '}',
    '',
    '/** null is an unreadable snapshot: the count is unknown, which is no evidence the jobs ended. */',
    'function ompBackgroundJobsExtra(count: number | null): Record<string, unknown> {',
    '  if (count === null) return { background_tasks_unknown: true }',
    '  return count > 0 ? { background_task_count: count } : {}',
    '}',
    '',
    'function watchOmpBackgroundJobs(',
    '  ctx: OmpJobsContext | undefined,',
    '  reported: number | null,',
    '  sinceRenew: number,',
    '  unreadable: number',
    '): void {',
    '  const sessionId = getPostSessionMetadata(true).session_id',
    '  const delay = unreadable >= OMP_BACKGROUND_JOBS_UNREADABLE_BACKOFF_POLLS',
    '    ? OMP_BACKGROUND_JOBS_BACKOFF_MS',
    '    : OMP_BACKGROUND_JOBS_POLL_MS',
    '  ompBackgroundJobsTimer = setTimeout(() => {',
    '    ompBackgroundJobsTimer = null',
    '    // Why: a replaced session reports for itself; never settle it from the old one.',
    '    if (getPostSessionMetadata(true).session_id !== sessionId) return',
    '    const read = runningOmpAsyncJobCount(ctx)',
    '    // Why keep the last count: an unreadable snapshot is no evidence the jobs finished.',
    '    if (read === null) {',
    '      watchOmpBackgroundJobs(ctx, reported, sinceRenew, unreadable + 1)',
    '      return',
    '    }',
    '    const renew = read !== reported || sinceRenew + 1 >= OMP_BACKGROUND_JOBS_RENEW_POLLS',
    "    if (renew) post('agent_end', ompBackgroundJobsExtra(read))",
    '    if (read > 0) watchOmpBackgroundJobs(ctx, read, renew ? 0 : sinceRenew + 1, 0)',
    '  }, delay)',
    "  if (typeof ompBackgroundJobsTimer.unref === 'function') ompBackgroundJobsTimer.unref()",
    '}',
    '',
    '/** The agent_end fields for a finished turn; keeps watching while its jobs run. */',
    'function ompTurnEndJobs(ctx: OmpJobsContext | undefined): Record<string, unknown> {',
    '  stopOmpBackgroundJobsWatch()',
    '  const read = runningOmpAsyncJobCount(ctx)',
    '  // Why watch an unreadable snapshot too: its unknown count settles once a read succeeds.',
    '  if (read === null || read > 0) watchOmpBackgroundJobs(ctx, read, 0, read === null ? 1 : 0)',
    '  return ompBackgroundJobsExtra(read)',
    '}',
    ''
  ]
}
