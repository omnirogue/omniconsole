// Why: a parked OMP tool produces no more lifecycle events until the user answers.
// Renew from that live process so a restarted receiver can recover its prompt
// without trusting an old status file or retrying the tool.
export function getOmpApprovalRefreshSourceLines(): string[] {
  return [
    'const OMP_APPROVAL_REFRESH_MS = 10_000',
    'type OmpApprovalContext = { sessionManager?: { getSessionId?: () => unknown; getSessionFile?: () => unknown } }',
    'type PendingOmpApproval = {',
    '  payload: Record<string, unknown>',
    '  ctx: OmpApprovalContext',
    '  sessionId: string',
    '  sessionFile: string',
    '  timer: ReturnType<typeof setTimeout> | null',
    '}',
    'let pendingOmpApproval: PendingOmpApproval | null = null',
    '',
    'function stopOmpApprovalRefresh(toolCallId?: unknown): void {',
    '  const pending = pendingOmpApproval',
    '  if (!pending || (toolCallId !== undefined && toolCallId !== pending.payload.tool_call_id)) return',
    '  pendingOmpApproval = null',
    '  if (pending.timer !== null) clearTimeout(pending.timer)',
    "  if (pendingPost?.hookEventName === 'tool_approval_requested' &&",
    '      pendingPost.extra.tool_call_id === pending.payload.tool_call_id &&',
    '      pendingPost.metadata.session_id === pending.sessionId) {',
    '    pendingPost = null',
    '  }',
    '}',
    '',
    'function scheduleOmpApprovalRefresh(pending: PendingOmpApproval): void {',
    '  pending.timer = setTimeout(() => {',
    '    if (pendingOmpApproval !== pending) return',
    '    pending.timer = null',
    '    try {',
    '      const manager = pending.ctx.sessionManager',
    '      if (manager?.getSessionId?.() !== pending.sessionId ||',
    '          manager?.getSessionFile?.() !== pending.sessionFile ||',
    '          getPostSessionMetadata(true).session_id !== pending.sessionId) {',
    '        stopOmpApprovalRefresh()',
    '        return',
    '      }',
    "      post('tool_approval_requested', pending.payload)",
    '      scheduleOmpApprovalRefresh(pending)',
    '    } catch {',
    '      stopOmpApprovalRefresh()',
    '    }',
    '  }, OMP_APPROVAL_REFRESH_MS)',
    "  if (typeof pending.timer.unref === 'function') pending.timer.unref()",
    '}',
    '',
    'function startOmpApprovalRefresh(',
    '  event: { toolCallId?: unknown; sessionId?: unknown },',
    '  ctx: OmpApprovalContext | undefined,',
    '  payload: Record<string, unknown>',
    '): void {',
    '  stopOmpApprovalRefresh()',
    "  if (typeof event.toolCallId !== 'string' || !event.toolCallId || !ctx) return",
    '  try {',
    '    const sessionId = ctx.sessionManager?.getSessionId?.()',
    '    const sessionFile = ctx.sessionManager?.getSessionFile?.()',
    "    if (typeof sessionId !== 'string' || !sessionId || typeof sessionFile !== 'string' || !sessionFile ||",
    '        (event.sessionId !== undefined && event.sessionId !== sessionId)) return',
    '    const pending: PendingOmpApproval = { payload, ctx, sessionId, sessionFile, timer: null }',
    '    pendingOmpApproval = pending',
    '    scheduleOmpApprovalRefresh(pending)',
    '  } catch {',
    '    // Missing or disposed native context cannot authorize a repeated status.',
    '  }',
    '}',
    ''
  ]
}
