it('safeNextSteps keeps offered order and drops risky steps', () => {
  const step = (id: string, risk: NextStepSuggestion['risk']): NextStepSuggestion => ({
    id,
    title: id,
    prompt: id,
    risk,
    kind: 'other'
  })
  expect(
    safeNextSteps({ suggestions: [step('a', 'safe'), step('b', 'risky'), step('c', 'safe')] }).map(
      (s) => s.id
    )
  ).toEqual(['a', 'c'])
})
